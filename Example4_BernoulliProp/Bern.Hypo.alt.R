data.generate <- function ( theta , m1,  pi1 , pi0 ) {
  
  m <- length ( theta )  
  
  X <- theta * rbinom ( m , m1 , pi1 ) + ( 1 - theta ) * rbinom ( m , m1 , pi0 )
  
  X
  
}

data.generate.n <- function ( theta , m1,  pi1 , pi0 , n ) {
  
  replicate ( n , data.generate (theta , m1,  pi1 , pi0 ) ) 
  
}

data.generate.x <- function ( theta , m1,  pi1 , pi0 , X ) {
  
  u <-  data.generate ( theta , m1,  pi1 , pi0 ) 
  
  cbind ( X , u )
  
}

