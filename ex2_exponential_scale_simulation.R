###############################################################
# Example 2: Exponential Scale Testing
#
# Corresponds to:
#   Example 2 (Ex2), Table 1
#
# Problem:
#   Sequential large-scale multiple testing for
#   H0: X ~ Exp(1)
#   H1: X ~ Exp(1.2)
#
# This script performs the simulation study for Example 2
# using the Oracle Intersection (OI) and Data-driven
# Intersection (DI) procedures.
#
# Required code:
#   exp.hypo.R
#
# Output:
#   A vector containing:
#     • Monte Carlo estimates of ASN, FDR and FNR
#       for the OI and DI procedures,
#     • Monte Carlo standard errors of these estimates.
###############################################################



library ( parallel )

ncore = detectCores ( ) - 2

cl = makeCluster ( ncore )

clusterSetRNGStream(cl, 12345)

clusterEvalQ ( cl , {
  

  source("Functions/EstNull.func.R.txt")
  
  source("Functions/epsest.func.R.txt")
  
  source("Functions/lin.itp.R.txt")
  
  source("Functions/adpt.cutz.R.txt")
  
  source("Functions/adaptZ.func.R.txt")
  
  source("Functions/Seq.adap.txt")
  
  source("Functions/lfdr.gen.R.txt")
  
  source("Functions/jin.cai.pi0.R.txt")
  
  source("exp.hypo.R")
  
  
} )

matrix <- cbind ( rep ( c ( 100 , 500 , 1000 , 5000 ) , each = 3 ) , rep ( c ( 0.2 , 0.5 , 0.8 ) , 4 ) )

Nrep <- 200

exp.test <- function ( x ) {
  
  r1 <- parSapply ( cl , 1 : Nrep , function ( i , ... ) { x <- exp.hypo (  x[1], x[2], 20 , 1 , 1.2 , 0.05 , 0.1 ) } )
  
  c ( rowMeans ( r1 ) , apply ( r1 , 1 , sd ) / sqrt ( Nrep ) )
  
}

apply ( matrix , 1 , exp.test )

stopCluster(cl)


