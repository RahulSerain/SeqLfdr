Nrep <- 200

t.test.2 <- function ( x ) {
  
  r1 <- parSapply ( cl , 1 : Nrep , function ( i , ... ) { x <- two.side.t(x[1], x[2:4] , 10 , 0.5 , 0 , 1 , -1 , 0.05, 0.1) } )
  
  c ( rowMeans ( r1 ) , apply ( r1 , 1 , sd ) / sqrt ( Nrep ) )
  
}

