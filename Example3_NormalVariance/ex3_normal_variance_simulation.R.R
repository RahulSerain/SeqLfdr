# Corresponds to:
#   Example 3 (Ex3), Table 1
#
# Problem:
#   Sequential large-scale multiple testing for
#   H0: X ~ N(0,1)
#   H1: X ~ N(0,1.2^2)
#
# This script performs the simulation study for Example 3
